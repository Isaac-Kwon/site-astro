// @ts-check
import { defineConfig } from 'astro/config';
import remarkMath from 'remark-math';
import rehypeMathjax from 'rehype-mathjax';
import rehypeExternalLinks from 'rehype-external-links';
import prefixBase from './scripts/prefix-base.mjs';

// Production builds use "/" (served at https://isaack.dev/).
// The preview deploy sets SITE_BASE=/site-astro/ (served at isaack.dev/site-astro/).
const base = process.env.SITE_BASE || '/';

export default defineConfig({
  site: 'https://isaack.dev',
  base,
  // Jekyll produced /path/ URLs (pretty permalinks); keep them byte-identical.
  trailingSlash: 'always',
  build: { format: 'directory' },
  // /sitemap.xml is generated by src/pages/sitemap.xml.ts (same URL as Jekyll).
  integrations: [prefixBase(base)],
  markdown: {
    // Only $$...$$ is math (kramdown convention); a single $ stays literal text.
    remarkPlugins: [[remarkMath, { singleDollarTextMath: false }]],
    rehypePlugins: [
      rehypeMathjax,
      [rehypeExternalLinks, { target: '_blank', rel: ['noopener', 'noreferrer'] }],
    ],
    shikiConfig: { theme: 'github-light' },
  },
});
